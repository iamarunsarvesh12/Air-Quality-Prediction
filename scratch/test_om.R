library(curl)
library(jsonlite)
h <- curl::new_handle(timeout = 10)
resp <- curl::curl_fetch_memory("https://air-quality-api.open-meteo.com/v1/air-quality?latitude=13.0827&longitude=80.2707&current=pm10,pm2_5,carbon_monoxide,nitrogen_dioxide,sulphur_dioxide,ozone,ammonia&hourly=pm10,pm2_5,carbon_monoxide,nitrogen_dioxide,sulphur_dioxide,ozone,ammonia&forecast_days=2", handle = h)
cat("Status code:", resp$status_code, "\n")
json <- jsonlite::fromJSON(rawToChar(resp$content))
print(names(json))
print(json$current_units)
print(json$current)
